// preview (FR 1.4)
// ---------------------------------------------------------------------------

/**
 * The preview is served by an authorising endpoint, so it cannot be handed to
 * `<Document file="/api/v1/...">` -- react-pdf would fetch it without the
 * bearer token. Pull the bytes through the API client and give the viewer an
 * object URL instead.
 *
 * Non-PDF uploads (scans, photos) get a downscaled first-page image from the
 * server rather than a PDF, so the content type decides how to render.
 */
function PreviewBody({ listingId, pageCount }: { listingId: string; pageCount?: number | null }) {
  const [objectUrl, setObjectUrl] = useState<string | null>(null)
  const [mime, setMime] = useState<string>('')
  const [error, setError] = useState<unknown>(null)
  const [numPages, setNumPages] = useState<number | null>(null)
  const [pageNumber, setPageNumber] = useState(1)
  const [width, setWidth] = useState(560)
  const frameRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    let cancelled = false
    let created: string | null = null

    api
      .blob(`/materials/${listingId}/preview`)
      .then(({ blob }) => {
        if (cancelled) return
        created = URL.createObjectURL(blob)
        setMime(blob.type)
        setObjectUrl(created)
      })
      .catch((cause: unknown) => {
        if (!cancelled) setError(cause)
      })

    return () => {
      cancelled = true
      if (created) URL.revokeObjectURL(created)
    }
  }, [listingId])

  // The page must be rendered at a real pixel width, which is the one genuinely
  // computed value on this screen.
  useEffect(() => {
    const element = frameRef.current
    if (!element) return
    const observer = new ResizeObserver((entries) => {
      const measured = entries[0]?.contentRect.width
      if (measured && measured > 0) setWidth(Math.floor(measured))
    })
    observer.observe(element)
    return () => observer.disconnect()
  }, [])

  if (error) {
    return <ErrorBox error={error} title="Could not load the preview" />
  }

  const isImage = mime.startsWith('image/')
  const total = numPages ?? 0

  return (
    <div>
      <p className="mb-3 rounded-lg bg-brand-50 px-3 py-2 text-xs leading-relaxed text-brand-900">
        This is a {PREVIEW_PAGES}-page preview, generated by the server when the file was uploaded.
        The full document is released only after a transaction completes.
        {pageCount ? ` The complete file has ${pageCount} pages.` : ''}
      </p>

      <div
        ref={frameRef}
        className="flex min-h-[24rem] items-center justify-center overflow-hidden rounded-lg bg-slate-100 p-2"
      >
        {!objectUrl ? (
          <div className="flex flex-col items-center gap-2 py-16 text-slate-400">
            <Spinner size="lg" label={null} />
            <p className="text-sm text-slate-500">Fetching the preview…</p>
          </div>
        ) : isImage ? (
          <img
            src={objectUrl}
            alt="First page of the uploaded material"
            className="max-h-[60vh] w-auto max-w-full rounded shadow-card"
          />
        ) : (
          <Document
            file={objectUrl}
            onLoadSuccess={(pdf) => {
              setNumPages(pdf.numPages)
              setPageNumber(1)
            }}
            onLoadError={(cause) => setError(cause)}
            loading={
              <div className="flex flex-col items-center gap-2 py-16 text-slate-400">
                <Spinner size="lg" label={null} />
                <p className="text-sm text-slate-500">Rendering…</p>
              </div>
            }
            error={<p className="py-16 text-sm text-slate-500">This preview could not be rendered.</p>}
          >
            <PdfPage
              pageNumber={pageNumber}
              width={width}
              renderTextLayer={false}
              renderAnnotationLayer={false}
              className="shadow-card"
            />
          </Document>
        )}
      </div>

      {!isImage && total > 0 ? (
        <div className="mt-3 flex items-center justify-center gap-3">
          <Button
            variant="ghost"
            size="sm"
            disabled={pageNumber <= 1}
            onClick={() => setPageNumber((current) => Math.max(1, current - 1))}
          >
            Previous
          </Button>
          <p className="text-sm tabular-nums text-slate-600">
            Page {pageNumber} of {total}
          </p>
          <Button
            variant="ghost"
            size="sm"
            disabled={pageNumber >= total}
            onClick={() => setPageNumber((current) => Math.min(total, current + 1))}
          >
            Next
          </Button>
        </div>
      ) : null}
    </div>
  )
}

