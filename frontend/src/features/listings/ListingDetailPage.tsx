/*
 * PDF.js needs its worker as a separate file. Vite resolves this URL at build
 * time out of the `pdfjs-dist` copy that react-pdf depends on, so nothing is
 * fetched from a CDN.
 */
pdfjs.GlobalWorkerOptions.workerSrc = new URL(
  'pdfjs-dist/build/pdf.worker.min.mjs',
  import.meta.url,
).toString()

/** Server-side slice size. Used for the copy only. */
const PREVIEW_PAGES = 3
const DEFAULT_RENTAL_DAYS = 14

