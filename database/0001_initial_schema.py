REPORTS = """
CREATE TABLE reports (
    report_id       TEXT PRIMARY KEY,
    reporter_id     TEXT NOT NULL REFERENCES users(user_id),
    listing_id      TEXT NOT NULL REFERENCES study_materials(listing_id),
    reason          TEXT NOT NULL
                    CHECK (reason IN ('INAPPROPRIATE','FAKE','COPYRIGHT','SPAM','OTHER')),
    details         TEXT,
    status          TEXT NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
    created_at      TEXT NOT NULL,
    resolved_by     TEXT REFERENCES users(user_id),
    resolved_at     TEXT,
    resolution_note TEXT,
    UNIQUE (reporter_id, listing_id)
)
"""

REVIEWS = """
CREATE TABLE reviews (
    review_id      TEXT PRIMARY KEY,
    transaction_id TEXT NOT NULL REFERENCES transactions(transaction_id),
    reviewer_id    TEXT NOT NULL REFERENCES users(user_id),
    reviewee_id    TEXT NOT NULL REFERENCES users(user_id),
    listing_id     TEXT NOT NULL REFERENCES study_materials(listing_id),
    rating         INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment        TEXT,
    created_at     TEXT NOT NULL,
    UNIQUE (transaction_id, reviewer_id),
    CHECK (reviewer_id <> reviewee_id)
)
"""

