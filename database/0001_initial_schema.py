STUDY_MATERIALS = """
CREATE TABLE study_materials (
    listing_id       TEXT PRIMARY KEY,
    uploader_id      TEXT NOT NULL REFERENCES users(user_id),
    campus_id        TEXT NOT NULL REFERENCES campuses(campus_id),
    title            TEXT NOT NULL,
    description      TEXT,
    course_code      TEXT NOT NULL,
    course_code_norm TEXT NOT NULL,
    department       TEXT NOT NULL,
    semester         TEXT NOT NULL,
    edition          TEXT,
    listing_type     TEXT NOT NULL
                     CHECK (listing_type IN ('SELL','RENT','EXCHANGE','FREE')),
    price            REAL,
    status           TEXT NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING','APPROVED','REJECTED',
                                       'RESERVED','COMPLETED','REMOVED')),
    file_path        TEXT NOT NULL,
    preview_path     TEXT,
    page_count       INTEGER,
    file_hash        TEXT NOT NULL,
    upload_date      TEXT NOT NULL,
    moderated_by     TEXT REFERENCES users(user_id),
    moderated_at     TEXT,
    moderation_note  TEXT,
    CHECK ((listing_type IN ('EXCHANGE','FREE') AND price IS NULL)
        OR (listing_type IN ('SELL','RENT')     AND price IS NOT NULL AND price >= 0))
)
"""

# FTS5 external-content index backing FR 1.2 keyword search. `content=` means
# the index stores no copy of the text; the triggers below keep it in step.
MATERIALS_FTS = """
CREATE VIRTUAL TABLE materials_fts USING fts5(
    title,
    course_code,
    department,
    description,
    content='study_materials',
    content_rowid='rowid'
)
"""

FTS_TRIGGERS = [
    """
    CREATE TRIGGER study_materials_ai AFTER INSERT ON study_materials BEGIN
        INSERT INTO materials_fts(rowid, title, course_code, department, description)
        VALUES (new.rowid, new.title, new.course_code, new.department, new.description);
    END
    """,
    """
    CREATE TRIGGER study_materials_ad AFTER DELETE ON study_materials BEGIN
        INSERT INTO materials_fts(materials_fts, rowid, title, course_code, department, description)
        VALUES ('delete', old.rowid, old.title, old.course_code, old.department, old.description);
    END
    """,
    """
    CREATE TRIGGER study_materials_au AFTER UPDATE ON study_materials BEGIN
        INSERT INTO materials_fts(materials_fts, rowid, title, course_code, department, description)
        VALUES ('delete', old.rowid, old.title, old.course_code, old.department, old.description);
        INSERT INTO materials_fts(rowid, title, course_code, department, description)
        VALUES (new.rowid, new.title, new.course_code, new.department, new.description);
    END
    """,
]

