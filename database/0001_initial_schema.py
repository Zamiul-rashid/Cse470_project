REQUESTS = """
CREATE TABLE requests (
    request_id       TEXT PRIMARY KEY,
    requester_id     TEXT NOT NULL REFERENCES users(user_id),
    course_code      TEXT NOT NULL,
    course_code_norm TEXT NOT NULL,
    department       TEXT,
    edition          TEXT,
    listing_type     TEXT CHECK (listing_type IN ('SELL','RENT','EXCHANGE','FREE')),
    max_price        REAL,
    campus_id        TEXT REFERENCES campuses(campus_id),
    description      TEXT,
    status           TEXT NOT NULL DEFAULT 'OPEN'
                     CHECK (status IN ('OPEN','MATCHED','CLOSED')),
    created_at       TEXT NOT NULL
)
"""

WISHLISTS = """
CREATE TABLE wishlists (
    wishlist_id  TEXT PRIMARY KEY,
    user_id      TEXT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE
)
"""

WISHLIST_ITEMS = """
CREATE TABLE wishlist_items (
    wishlist_id  TEXT NOT NULL REFERENCES wishlists(wishlist_id) ON DELETE CASCADE,
    listing_id   TEXT NOT NULL REFERENCES study_materials(listing_id) ON DELETE CASCADE,
    added_at     TEXT NOT NULL,
    PRIMARY KEY (wishlist_id, listing_id)
)
"""

CONVERSATIONS = """
CREATE TABLE conversations (
    conversation_id TEXT PRIMARY KEY,
    user_a_id       TEXT NOT NULL REFERENCES users(user_id),
    user_b_id       TEXT NOT NULL REFERENCES users(user_id),
    listing_id      TEXT REFERENCES study_materials(listing_id),
    created_at      TEXT NOT NULL,
    last_message_at TEXT,
    CHECK (user_a_id < user_b_id),
    UNIQUE (user_a_id, user_b_id, listing_id)
)
"""

MESSAGES = """
CREATE TABLE messages (
    message_id      TEXT PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
    sender_id       TEXT NOT NULL REFERENCES users(user_id),
    content         TEXT NOT NULL,
    timestamp       TEXT NOT NULL,
    read_at         TEXT
)
"""

